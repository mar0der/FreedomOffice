//! Small helpers: random ids and tokens, hashing, time, name validation, passwords.

use argon2::password_hash::{PasswordHash, PasswordHasher, PasswordVerifier, SaltString};
use argon2::Argon2;
use sha2::{Digest, Sha256};

pub fn random_bytes<const N: usize>() -> [u8; N] {
    let mut b = [0u8; N];
    getrandom::fill(&mut b).expect("the operating system random number generator failed");
    b
}

pub fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// Random 128-bit id (32 lowercase hex chars) for users, items and links.
pub fn new_id() -> String {
    hex(&random_bytes::<16>())
}

/// Ids are only ever generated by `new_id`; anything else is rejected before touching disk.
pub fn valid_id(s: &str) -> bool {
    s.len() == 32 && s.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// Base64url (no padding) of 32 random bytes: a bearer secret shown once to the client.
pub fn new_token() -> String {
    base64url(&random_bytes::<32>())
}

pub fn base64url(data: &[u8]) -> String {
    const A: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
    let mut out = String::with_capacity(data.len() * 4 / 3 + 3);
    for ch in data.chunks(3) {
        let n = (ch[0] as u32) << 16 | (*ch.get(1).unwrap_or(&0) as u32) << 8 | *ch.get(2).unwrap_or(&0) as u32;
        for i in 0..=ch.len() {
            out.push(A[(n >> (18 - 6 * i)) as usize & 63] as char);
        }
    }
    out
}

/// Tokens are stored as SHA-256 digests only.
pub fn token_hash(token: &str) -> Vec<u8> {
    Sha256::digest(token.as_bytes()).to_vec()
}

pub fn sha256_hex(data: &[u8]) -> String {
    hex(&Sha256::digest(data))
}

/// Constant-time byte comparison.
pub fn ct_eq(a: &[u8], b: &[u8]) -> bool {
    if a.len() != b.len() {
        return false;
    }
    a.iter().zip(b).fold(0u8, |acc, (x, y)| acc | (x ^ y)) == 0
}

pub fn now() -> i64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs() as i64).unwrap_or(0)
}

/// Unix seconds -> "2026-11-05T14:07:09Z".
pub fn iso(ts: i64) -> String {
    let days = ts.div_euclid(86400);
    let secs = ts.rem_euclid(86400);
    let (y, m, d) = civil_from_days(days);
    format!("{y:04}-{m:02}-{d:02}T{:02}:{:02}:{:02}Z", secs / 3600, secs % 3600 / 60, secs % 60)
}

/// Day number (days since 1970-01-01, UTC).
pub fn day_of(ts: i64) -> i64 {
    ts.div_euclid(86400)
}

fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719468;
    let era = z.div_euclid(146097);
    let doe = z.rem_euclid(146097);
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

/// Validates and normalizes a file or folder name.
pub fn clean_name(name: &str) -> Result<String, String> {
    let n = name.trim();
    if n.is_empty() {
        return Err("The name can't be empty.".into());
    }
    if n.chars().count() > 255 {
        return Err("The name is too long (255 characters at most).".into());
    }
    if n.chars().any(|c| c.is_control() || r#"/\:*?"<>|"#.contains(c)) {
        return Err(r#"A name can't contain any of these characters: / \ : * ? " < > |"#.into());
    }
    if n == "." || n == ".." {
        return Err("That name isn't allowed.".into());
    }
    Ok(n.to_string())
}

/// Usernames: letters, digits, '.', '-', '_' (1-64 chars).
pub fn valid_username(u: &str) -> bool {
    !u.is_empty() && u.len() <= 64 && u.chars().all(|c| c.is_ascii_alphanumeric() || ".-_".contains(c)) && !u.starts_with('.')
}

/// "Book.xlsx", 2 -> "Book (2).xlsx"
pub fn numbered_name(name: &str, n: u32) -> String {
    match name.rsplit_once('.') {
        Some((stem, ext)) if !stem.is_empty() => format!("{stem} ({n}).{ext}"),
        _ => format!("{name} ({n})"),
    }
}

pub fn hash_password(pw: &str) -> String {
    let salt = SaltString::encode_b64(&random_bytes::<16>()).expect("salt");
    Argon2::default().hash_password(pw.as_bytes(), &salt).expect("argon2id hashing").to_string()
}

pub fn verify_password(pw: &str, hash: &str) -> bool {
    match PasswordHash::new(hash) {
        Ok(h) => Argon2::default().verify_password(pw.as_bytes(), &h).is_ok(),
        Err(_) => false,
    }
}

/// Spends the same time as a real verification (unknown users must not answer faster).
pub fn dummy_verify(pw: &str) {
    static DUMMY: std::sync::OnceLock<String> = std::sync::OnceLock::new();
    let h = DUMMY.get_or_init(|| hash_password("freedomoffice-dummy-password"));
    let _ = verify_password(pw, h);
}

pub const MIN_PASSWORD: usize = 12;

const COMMON_PASSWORDS: &str = include_str!("common_passwords.txt");

fn is_common(lower: &str) -> bool {
    static SET: std::sync::OnceLock<std::collections::HashSet<&'static str>> = std::sync::OnceLock::new();
    let set = SET.get_or_init(|| COMMON_PASSWORDS.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).collect());
    // "Password2024!" is as weak as "password": also check without leading and trailing
    // digits and symbols.
    let core = lower.trim_matches(|c: char| !c.is_alphabetic());
    set.contains(lower) || set.contains(core)
}

/// The rules for every new or changed password: at least `MIN_PASSWORD` characters, not the
/// username (nor containing it), not a common password, not one character repeated.
pub fn check_new_password(pw: &str, username: &str) -> Result<(), String> {
    if pw.chars().count() < MIN_PASSWORD {
        return Err(format!("The password must be at least {MIN_PASSWORD} characters long."));
    }
    if pw.len() > 1024 {
        return Err("The password is too long.".into());
    }
    let lower = pw.to_lowercase();
    let user = username.trim().to_lowercase();
    if !user.is_empty() && (lower == user || (user.chars().count() >= 3 && lower.contains(&user))) {
        return Err("The password can't contain the username.".into());
    }
    let mut chars = lower.chars();
    let first = chars.next();
    if chars.all(|c| Some(c) == first) {
        return Err("The password can't be one character repeated.".into());
    }
    if is_common(&lower) {
        return Err("That password is too common; choose one that is harder to guess.".into());
    }
    Ok(())
}

/// A random temporary password: 20 characters from an alphabet without look-alikes (about
/// 99 bits) in groups of four, e.g. "kq7m-x3tp-9wrd-hc4n-fz2v".
pub fn temp_password() -> String {
    const A: &[u8] = b"abcdefghjkmnpqrstuvwxyz23456789";
    let mut out = String::with_capacity(24);
    while out.len() < 24 {
        for b in random_bytes::<32>() {
            // Rejection sampling keeps every character equally likely.
            if out.len() >= 24 || (b as usize) >= 256 - 256 % A.len() {
                continue;
            }
            if out.len() % 5 == 4 {
                out.push('-');
            }
            out.push(A[b as usize % A.len()] as char);
        }
    }
    out
}

/// A temporary password that passes `check_new_password` for `username` (drawn again in the
/// unlikely case it doesn't, e.g. it happens to contain a short username).
pub fn temp_password_for(username: &str) -> String {
    loop {
        let pw = temp_password();
        if check_new_password(&pw, username).is_ok() {
            return pw;
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn iso_dates() {
        assert_eq!(iso(0), "1970-01-01T00:00:00Z");
        assert_eq!(iso(951782400), "2000-02-29T00:00:00Z");
        assert_eq!(iso(1794060429), "2026-11-07T14:07:09Z");
        assert_eq!(day_of(86399), 0);
        assert_eq!(day_of(86400), 1);
    }

    #[test]
    fn names() {
        assert_eq!(clean_name("  Book.xlsx ").unwrap(), "Book.xlsx");
        for bad in ["", "  ", "a/b", "a\\b", "a:b", "a*b", "a?b", "a\"b", "a<b", "a>b", "a|b", "a\nb", "..", "."] {
            assert!(clean_name(bad).is_err(), "{bad:?}");
        }
        assert!(clean_name(&"x".repeat(255)).is_ok());
        assert!(clean_name(&"x".repeat(256)).is_err());
        assert_eq!(numbered_name("Book.xlsx", 2), "Book (2).xlsx");
        assert_eq!(numbered_name("Folder", 3), "Folder (3)");
        assert!(valid_username("ann.lee-2"));
        assert!(!valid_username("ann lee"));
        assert!(!valid_username(".x"));
    }

    #[test]
    fn ids_and_tokens() {
        let id = new_id();
        assert!(valid_id(&id));
        assert!(!valid_id("../../etc/passwd"));
        assert!(!valid_id(&id.to_uppercase()));
        assert_eq!(new_token().len(), 43);
        assert!(ct_eq(b"abc", b"abc"));
        assert!(!ct_eq(b"abc", b"abd"));
        assert!(!ct_eq(b"abc", b"ab"));
    }

    #[test]
    fn password_policy() {
        assert!(check_new_password("test-password-1", "bob").is_ok());
        assert!(check_new_password("short-pw", "bob").is_err(), "too short");
        assert!(check_new_password("aaaaaaaaaaaaaaaa", "bob").is_err(), "repeated");
        assert!(check_new_password("password1234", "bob").is_err(), "common");
        assert!(check_new_password("Password2024!", "bob").is_err(), "common plus digits");
        assert!(check_new_password("qwertyuiop123", "bob").is_err());
        assert!(check_new_password("!!Iloveyou!!", "bob").is_err());
        assert!(check_new_password("Alice.Wonder-77", "alice").is_err(), "contains the username");
        assert!(check_new_password("averylongusername", "AveryLongUsername").is_err(), "is the username");
        assert!(check_new_password("x-correct-horse-battery", "x").is_ok(), "one-letter usernames don't ban letters");
        assert!(check_new_password(&"ab".repeat(600), "bob").is_err(), "too long");
    }

    #[test]
    fn temp_passwords() {
        let a = temp_password();
        assert_eq!(a.len(), 24);
        assert_eq!(a.matches('-').count(), 4);
        assert_ne!(a, temp_password());
        assert!(check_new_password(&a, "someone").is_ok());
    }
}
